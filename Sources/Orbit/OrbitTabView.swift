import Foundation
import SwiftUI

/// Declares one tab's identity, root content and native tab label.
///
/// Use inside ``OrbitTabView``. Declaring an item stores its content/label
/// factories without invoking them. SwiftUI may evaluate both repeatedly while
/// rendering; keep one-shot side effects in the screen's lifecycle, not here.
/// Each tab gets its own Orbit-managed stack and environment router.
@MainActor
public struct OrbitTabItem {
    let tab: OrbitTab
    let makeContent: () -> AnyView
    let makeLabel: () -> AnyView

    /// Creates a tab declaration without constructing its screen or label yet.
    /// - Parameters:
    ///   - tab: Key matched by its exact concrete Swift type. Declare a type only
    ///     once per flow; instances may be recreated for later selection calls.
    ///   - content: Main-actor factory for the tab's root screen. Orbit supplies
    ///     the NavigationStack, so do not wrap it in another independent stack.
    ///   - label: Factory for standard SwiftUI tab-item content, such as a Label.
    public init<Content: View, Label: View>(
        _ tab: OrbitTab,
        @ViewBuilder content: @escaping () -> Content,
        @ViewBuilder label: @escaping () -> Label
    ) {
        self.tab = tab
        self.makeContent = { AnyView(content()) }
        self.makeLabel = { AnyView(label()) }
    }
}

/// Builds ordered tab declarations for ``OrbitTabView``.
///
/// Supports individual items, `if`, `if/else` and `for` statements. The builder
/// executes when a tab-flow declaration is created; it is not a dynamic source
/// of tabs after that flow has started. These public methods are compiler hooks,
/// not commands consumers normally call directly.
@MainActor
@resultBuilder
public enum OrbitTabBuilder {
    /// Converts a single tab expression into an ordered declaration component.
    /// - Parameter item: The tab declaration in the builder expression.
    /// - Returns: A component containing that one item.
    public static func buildExpression(_ item: OrbitTabItem) -> [OrbitTabItem] {
        [item]
    }

    /// Combines declaration components, preserving source order.
    /// - Parameter components: Components generated from the builder block.
    /// - Returns: Their flattened tab declarations; an empty block returns `[]`.
    public static func buildBlock(_ components: [OrbitTabItem]...) -> [OrbitTabItem] {
        components.flatMap { $0 }
    }

    /// Handles an `if` branch without an `else`.
    /// - Parameter component: Declarations from the branch, or `nil` when skipped.
    /// - Returns: The branch declarations, or an empty component.
    public static func buildOptional(_ component: [OrbitTabItem]?) -> [OrbitTabItem] {
        component ?? []
    }

    /// Handles the first branch of an `if/else` declaration.
    /// - Parameter first: Declarations produced by the selected first branch.
    /// - Returns: Those declarations unchanged.
    public static func buildEither(first: [OrbitTabItem]) -> [OrbitTabItem] { first }

    /// Handles the second branch of an `if/else` declaration.
    /// - Parameter second: Declarations produced by the selected second branch.
    /// - Returns: Those declarations unchanged.
    public static func buildEither(second: [OrbitTabItem]) -> [OrbitTabItem] { second }

    /// Combines declarations generated by iterations of a `for` statement.
    /// - Parameter components: One declaration component per loop iteration.
    /// - Returns: All items in iteration order.
    public static func buildArray(_ components: [[OrbitTabItem]]) -> [OrbitTabItem] {
        components.flatMap { $0 }
    }
}

/// Visual tab-bar policy for an iOS ``OrbitTabView``.
///
/// Never changes navigation semantics, paths or selection. Ignored on macOS.
/// Destination content can also express native SwiftUI toolbar preferences.
public enum OrbitTabBarVisibility: Sendable {
    /// Apply SwiftUI's automatic visibility preference; the default.
    case automatic
    /// Request visibility even when the selected tab has pushed destinations.
    case visible
    /// Use automatic visibility at a tab's root and hide its bar for a nonempty path.
    case hiddenOnPush
}

/// An independent tab flow declared without bindings, tags or manual stack hosts.
///
/// Return this container from an Orbit `register` factory. Its ``OrbitTabFlow``
/// metadata identifies a root/modal flow, never a pushed entry.
/// Each tab gets independent history, a native label and an environment router.
///
/// Native ModifiedContent modifier chains preserve the flow automatically.
/// For Group, AnyView or transformations that hide the declaration, call
/// `wrapped` on this container and decorate the supplied flow inside its closure.
/// Custom wrappers can conform to OrbitTabFlow with a stable stored declaration.
/// Unannotated opaque containers cannot be inspected through public SwiftUI
/// APIs: misuse is reported on appearance, with empty content in release.
@MainActor
public struct OrbitTabView: OrbitTabFlow {
    @Environment(\.orbitContext) private var context
    let id = UUID()
    let items: [OrbitTabItem]
    private let tabBarVisibility: OrbitTabBarVisibility

    /// This flow's own stored declaration, used by modifier/wrapper metadata.
    public var orbitTabView: OrbitTabView { self }

    /// Creates a tab-flow declaration with lazy screen and label factories.
    /// - Parameters:
    ///   - tabBarVisibility: iOS visual preference; `.automatic` by default.
    ///   - content: Ordered ``OrbitTabItem`` declarations. Evaluated immediately
    ///     when this container is created, normally as a root/modal request is
    ///     prepared. The result is fixed for that flow's lifetime. Empty lists
    ///     and repeated tab types are rejected before a recognized flow starts.
    public init(
        tabBarVisibility: OrbitTabBarVisibility = .automatic,
        @OrbitTabBuilder content: () -> [OrbitTabItem]
    ) {
        self.items = content()
        self.tabBarVisibility = tabBarVisibility
    }

    /// The native tab container and independent stacks supplied by the matching host.
    public var body: some View {
        if let context, context.tabView?.id == id,
            let manager = context.tabManager
        {
            TabView(selection: Binding(
                get: { manager.selectedTab },
                set: { if let tab = $0 { manager.select(tab) } }
            )) {
                ForEach(items, id: \.tab) { item in
                    if let stack = manager.contexts[item.tab] {
                        OrbitNavigationHost(stack) { item.makeContent() }
                            .modifier(TabBarModifier(
                                policy: tabBarVisibility, context: stack
                            ))
                            .tabItem { item.makeLabel() }
                            .tag(item.tab as OrbitTab?)
                    }
                }
            }
        } else {
            Color.clear.onAppear {
                context?.owner?.reject(
                    "Preserve tab metadata with OrbitTabFlow or wrapped when registering this container."
                )
            }
        }
    }
}

@MainActor
private struct TabBarModifier: ViewModifier {
    let policy: OrbitTabBarVisibility
    let context: OrbitContext

    func body(content: Content) -> some View {
        #if os(iOS)
        content.toolbar(visibility, for: .tabBar)
        #else
        content
        #endif
    }

    private var visibility: Visibility {
        switch policy {
        case .automatic: .automatic
        case .visible: .visible
        case .hiddenOnPush: context.path.isEmpty ? .automatic : .hidden
        }
    }
}
